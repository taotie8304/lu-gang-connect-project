async function addDataCollectionZhCN() {
  const client = new MongoClient(MONGODB_URI);

  try {
    await client.connect();
    console.log('✅ 已连接到 MongoDB');

    const db = client.db(DATABASE_NAME);
    const collection = db.collection('system_contents');

    console.log('\n📝 处理: 鲁港通个人资料收集声明 (data_collection_zh-CN)');
    console.log(`   内容长度: ${DATA_COLLECTION_ZH_CN.length} 字符`);
    
    const existing = await collection.findOne({ key: 'data_collection_zh-CN' });
    
    if (existing) {
      console.log('   ⚠️  已存在，将更新内容...');
      
      const result = await collection.updateOne(
        { key: 'data_collection_zh-CN' },
        {
          $set: {
            content: DATA_COLLECTION_ZH_CN,
            title: '鲁港通个人资料收集声明',
            updatedAt: new Date()
          }
        }
      );
      
      console.log(`   ✅ 已更新 (匹配: ${result.matchedCount}, 修改: ${result.modifiedCount})`);
    } else {
      console.log('   📝 不存在，将创建新记录...');
      
      const result = await collection.insertOne({
        key: 'data_collection_zh-CN',
        title: '鲁港通个人资料收集声明',
        content: DATA_COLLECTION_ZH_CN,
        createdAt: new Date(),
        updatedAt: new Date()
      });
      
      console.log(`   ✅ 已创建 (ID: ${result.insertedId})`);
    }

    // 验证内容长度
    const doc = await collection.findOne({ key: 'data_collection_zh-CN' });
    console.log(`\n📊 内容统计：`);
    console.log(`   - 字符数：${doc.content.length}`);
    console.log(`   - 标题：${doc.title}`);
    console.log(`   - 更新时间：${doc.updatedAt}`);

  } catch (error) {
    console.error('❌ 操作失败:', error.message);
    process.exit(1);
  } finally {
    await client.close();
    console.log('\n✅ 数据库连接已关闭');
  }
}

